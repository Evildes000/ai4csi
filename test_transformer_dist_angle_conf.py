# Main Test Routine
# ============================================================
def test_dist_angle_conf(bw: int, checkpoint_path: str):
    """
    Load the test datasets for a given bandwidth, run inference, report results.

    Args:
        bw:               bandwidth (MHz) — used to construct file paths
        checkpoint_path:  path to trained .pth checkpoint
    """
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Using device: {device}")

    # ── Load model & scalers ──
    model, n_phase, n_sincos, scaler_dist, scaler_sincos, scaler_y = \
        load_checkpoint(checkpoint_path, device)

    # ── Test dataset parameters (must match csi_generator_test.py) ──
    NUM_LEVELS = 10
    conf_labels = [round(1.0 - lvl * 0.1, 1) for lvl in range(NUM_LEVELS)]
    #  [1.0, 0.9, 0.8, ..., 0.1]

    all_preds_arr = []
    all_labels_arr = []
    per_level_metrics = {}
    total_preprocess_time = 0.0
    total_inference_time = 0.0
    total_samples = 0

    for lvl in range(NUM_LEVELS):
        conf_val = conf_labels[lvl]
        wall_dB  = lvl * 10

        path_data = f"CSI_Test_Angle_Dataset_{bw}MHz_4Rx_conf_{conf_val}.npz"
        path_meta = f"metadata_CSI_Test_Angle_Dataset_{bw}MHz_4Rx_conf_{conf_val}.json"

        print(f"\n[{lvl+1}/{NUM_LEVELS}] Level {lvl}: "
              f"wall_loss={wall_dB} dB, confidence={conf_val}")

        if not os.path.exists(path_data):
            print(f"  SKIP: {path_data} not found. "
                  f"Run csi_generator_test.py first.")
            continue

        # ── Preprocess ──
        t0 = time.time()
        phase_data, label_array, meta = pre_processing_dist_angle_conf(
            path_to_data=path_data,
            path_to_meta=path_meta,
            confidence_label=conf_val,
        )
        total_preprocess_time += time.time() - t0

        # ── Inference ──
        predictions, avg_inf_us = predict_chunked(
            phase_data, model, n_phase, n_sincos,
            scaler_dist, scaler_sincos, scaler_y, device,
        )

        n_level = len(predictions)
        total_samples += n_level
        total_inference_time += avg_inf_us * n_level / 1e6  # convert µs → s

        all_preds_arr.append(predictions)
        all_labels_arr.append(label_array)

        # ── Per-level metrics ──
        m = compute_metrics(predictions, label_array)
        per_level_metrics[conf_val] = m

        print_metrics(f"Level {lvl} (conf={conf_val})", m, prefix="  ")

        # Free memory
        del phase_data, predictions, label_array

    # ── Combine all levels ──
    all_preds  = np.concatenate(all_preds_arr, axis=0)
    all_labels = np.concatenate(all_labels_arr, axis=0)

    overall_m = compute_metrics(all_preds, all_labels)

    print(f"\n{'='*70}")
    print(f"TEST SET OVERALL RESULTS — {bw} MHz")
    print(f"{'='*70}")
    print(f"  Total samples:  {total_samples:,}")
    print(f"  Preprocess:     {total_preprocess_time:.1f} s")
    print(f"  Inference:      {total_inference_time:.1f} s "
          f"({total_inference_time / total_samples * 1e6:.1f} us/sample)")
    print_metrics("OVERALL", overall_m)

    # ── LOS vs NLOS breakdown ──
    los_mask  = all_labels[:, 2] > 0.5
    nlos_mask = ~los_mask
    if los_mask.sum() > 0 and nlos_mask.sum() > 0:
        print(f"\n{'─'*70}")
        print("Breakdown by scenario:")
        los_m  = compute_metrics(all_preds[los_mask],  all_labels[los_mask])
        nlos_m = compute_metrics(all_preds[nlos_mask], all_labels[nlos_mask])
        print_metrics("LOS  (no wall)", los_m)
        print_metrics("NLOS (wall)",    nlos_m)

    # ── Per-level summary table ──
    print(f"\n{'─'*70}")
    print(f"{'Level':<6} {'Wall(dB)':<10} {'Conf':<6} "
          f"{'Dist MAE':<12} {'Angle MAE':<12} {'Conf MAE':<12}")
    print(f"{'─'*70}")
    for conf_val in sorted(per_level_metrics.keys(), reverse=True):
        m = per_level_metrics[conf_val]
        wall_dB = int(round((1.0 - conf_val) * 100))
        print(f"{int((1.0 - conf_val) * 10):<6} "
              f"{wall_dB:<10} "
              f"{conf_val:<6} "
              f"{m['mae_dist']:<12.4f} "
              f"{m['mae_angle']:<12.2f} "
              f"{m['mae_conf']:<12.4f}")

    # ── Visualize ──
    visualize_results(all_preds, all_labels, per_level_metrics, meta, bw)

    return overall_m, per_level_metrics, all_preds, all_labels


