"""
Test script for TransformerDistAngleConfEstimator model trained by
train_transformer_dist_angle_conf.py.

Loads a trained checkpoint and evaluates on the test datasets generated by
csi_generator_test.py.  The test datasets use **different** distances, angles,
and random seed — guaranteeing zero overlap with training data.

Reports:
  - Overall MAE / RMSE for distance, angle, confidence
  - Per-obstruction-level breakdown
  - Inference time per sample
  - Comprehensive visualizations saved to transformer_figures/
"""

